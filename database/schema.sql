-- MobileGIS PG2. Run as database owner, not the web application role.
-- Raster bytes stay in file/object storage; PostgreSQL stores spatial vectors,
-- validated measurements, versions, provenance, and the asset catalog.
CREATE EXTENSION IF NOT EXISTS postgis;
CREATE SCHEMA IF NOT EXISTS mobilegis;
CREATE TABLE IF NOT EXISTS mobilegis.schema_migrations (
  version integer PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS mobilegis.boundary_versions (
  id text PRIMARY KEY, reference_year integer NOT NULL,
  description text NOT NULL, metadata jsonb NOT NULL DEFAULT '{}'
);
CREATE TABLE IF NOT EXISTS mobilegis.admin_units (
  boundary_id text REFERENCES mobilegis.boundary_versions(id), code text NOT NULL,
  name text NOT NULL, properties jsonb NOT NULL,
  geom geometry(MultiPolygon,4326) NOT NULL,
  PRIMARY KEY(boundary_id,code), CHECK(ST_IsValid(geom)), CHECK(NOT ST_IsEmpty(geom))
);
CREATE INDEX IF NOT EXISTS admin_units_geom ON mobilegis.admin_units USING gist(geom);
CREATE TABLE IF NOT EXISTS mobilegis.datasets (
  id text PRIMARY KEY, title text NOT NULL,
  kind text NOT NULL CHECK(kind IN ('research','user_points','demo')),
  boundary_id text REFERENCES mobilegis.boundary_versions(id),
  parent_id text REFERENCES mobilegis.datasets(id),
  metadata jsonb NOT NULL DEFAULT '{}', imported_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS mobilegis.unit_observations (
  dataset_id text REFERENCES mobilegis.datasets(id), boundary_id text NOT NULL,
  code text NOT NULL, year integer NOT NULL CHECK(year BETWEEN 2020 AND 2025),
  sampled_pixels integer NOT NULL CHECK(sampled_pixels>0),
  dates date[] NOT NULL DEFAULT '{}', payload jsonb NOT NULL,
  PRIMARY KEY(dataset_id,code,year),
  FOREIGN KEY(boundary_id,code) REFERENCES mobilegis.admin_units(boundary_id,code)
);
CREATE INDEX IF NOT EXISTS observations_filter ON mobilegis.unit_observations(dataset_id,year,code);
CREATE TABLE IF NOT EXISTS mobilegis.satellite_scenes (
  dataset_id text REFERENCES mobilegis.datasets(id), year integer NOT NULL,
  scene_id text NOT NULL, acquisition_date date NOT NULL, metadata jsonb NOT NULL,
  PRIMARY KEY(dataset_id,year,scene_id), CHECK(extract(year FROM acquisition_date)=year)
);
CREATE TABLE IF NOT EXISTS mobilegis.observation_scenes (
  dataset_id text NOT NULL, code text NOT NULL, year integer NOT NULL, scene_id text NOT NULL,
  PRIMARY KEY(dataset_id,code,year,scene_id),
  FOREIGN KEY(dataset_id,code,year) REFERENCES mobilegis.unit_observations(dataset_id,code,year),
  FOREIGN KEY(dataset_id,year,scene_id) REFERENCES mobilegis.satellite_scenes(dataset_id,year,scene_id)
);
CREATE TABLE IF NOT EXISTS mobilegis.landcover_statistics (
  dataset_id text REFERENCES mobilegis.datasets(id), boundary_id text NOT NULL,
  code text NOT NULL, year integer NOT NULL CHECK(year=2021), payload jsonb NOT NULL,
  PRIMARY KEY(dataset_id,code,year),
  FOREIGN KEY(boundary_id,code) REFERENCES mobilegis.admin_units(boundary_id,code)
);
CREATE TABLE IF NOT EXISTS mobilegis.point_observations (
  dataset_id text REFERENCES mobilegis.datasets(id), name text NOT NULL,
  year integer NOT NULL CHECK(year BETWEEN 2020 AND 2025),
  lat double precision NOT NULL CHECK(lat BETWEEN -90 AND 90),
  lon double precision NOT NULL CHECK(lon BETWEEN -180 AND 180),
  geom geometry(Point,4326) GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(lon,lat),4326)) STORED,
  payload jsonb NOT NULL, PRIMARY KEY(dataset_id,name,year)
);
CREATE INDEX IF NOT EXISTS points_geom ON mobilegis.point_observations USING gist(geom);
-- Physically separate editable practice data from read-only research and user CSV.
CREATE TABLE IF NOT EXISTS mobilegis.demo_observations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK(length(trim(name)) BETWEEN 1 AND 150),
  lat double precision NOT NULL CHECK(lat BETWEEN -90 AND 90),
  lon double precision NOT NULL CHECK(lon BETWEEN -180 AND 180),
  year integer NOT NULL CHECK(year BETWEEN 2020 AND 2025),
  lst double precision NOT NULL CHECK(lst BETWEEN -80 AND 100),
  ndvi double precision NOT NULL CHECK(ndvi BETWEEN -1 AND 1),
  tvdi double precision NOT NULL CHECK(tvdi BETWEEN 0 AND 1),
  source text NOT NULL CHECK(length(trim(source)) BETWEEN 1 AND 500),
  geom geometry(Point,4326) GENERATED ALWAYS AS (ST_SetSRID(ST_MakePoint(lon,lat),4326)) STORED,
  updated_at timestamptz NOT NULL DEFAULT now(), UNIQUE(name,year)
);
CREATE INDEX IF NOT EXISTS demo_year ON mobilegis.demo_observations(year);
CREATE INDEX IF NOT EXISTS demo_geom ON mobilegis.demo_observations USING gist(geom);
CREATE TABLE IF NOT EXISTS mobilegis.audit_log (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, changed_at timestamptz NOT NULL DEFAULT now(),
  actor text NOT NULL DEFAULT current_user, operation text NOT NULL,
  record_id bigint NOT NULL, before_value jsonb, after_value jsonb
);
CREATE OR REPLACE FUNCTION mobilegis.audit_demo() RETURNS trigger LANGUAGE plpgsql
SECURITY DEFINER SET search_path = pg_catalog, mobilegis AS $$
BEGIN
  INSERT INTO mobilegis.audit_log(actor,operation,record_id,before_value,after_value)
  VALUES(session_user,TG_OP,COALESCE(NEW.id,OLD.id),
    CASE WHEN TG_OP='INSERT' THEN NULL ELSE to_jsonb(OLD)-'geom' END,
    CASE WHEN TG_OP='DELETE' THEN NULL ELSE to_jsonb(NEW)-'geom' END);
  RETURN COALESCE(NEW,OLD);
END $$;
REVOKE ALL ON FUNCTION mobilegis.audit_demo() FROM PUBLIC;
DROP TRIGGER IF EXISTS demo_audit ON mobilegis.demo_observations;
CREATE TRIGGER demo_audit AFTER INSERT OR UPDATE OR DELETE ON mobilegis.demo_observations
 FOR EACH ROW EXECUTE FUNCTION mobilegis.audit_demo();
CREATE TABLE IF NOT EXISTS mobilegis.asset_catalog (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  dataset_id text NOT NULL REFERENCES mobilegis.datasets(id),
  relative_path text NOT NULL CHECK(relative_path NOT LIKE '%..%' AND relative_path NOT LIKE '/%'),
  kind text NOT NULL, size_bytes bigint NOT NULL CHECK(size_bytes>=0),
  sha256 text NOT NULL CHECK(length(sha256)=64), metadata jsonb NOT NULL DEFAULT '{}',
  UNIQUE(dataset_id,relative_path)
);
CREATE TABLE IF NOT EXISTS mobilegis.documents (
  key text PRIMARY KEY, payload jsonb NOT NULL, sha256 text NOT NULL
);
